import React from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import App from './App.tsx';
import {lazy,Suspense} from 'react';
const ScreenPage=lazy(()=>import('./screening/ScreenPage'));
const screeningRoute=window.location.pathname.replace(/\/$/,'')==='/screen';
import './styles.css';
const queryClient = new QueryClient({defaultOptions:{queries:{retry:1,staleTime:30_000,refetchOnWindowFocus:false}}});
createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={queryClient}>{screeningRoute?<Suspense fallback={<p className="wrap" role="status">Opening screening workspace…</p>}><ScreenPage/></Suspense>:<App />}</QueryClientProvider></React.StrictMode>);
